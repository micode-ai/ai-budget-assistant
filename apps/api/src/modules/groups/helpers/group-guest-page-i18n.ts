export const GROUP_GUEST_TRANSLATIONS: Record<string, Dict> = { en, pl, de, es, fr, ru, ua, be, nl };

export interface GroupGuestStrings {
  lang: string;
  t: (key: GroupStrKey, ...args: (string | number)[]) => string;
}

export function getGroupGuestStrings(lang: string): GroupGuestStrings {
  const dict = GROUP_GUEST_TRANSLATIONS[lang] ?? en;
  return {
    lang: GROUP_GUEST_TRANSLATIONS[lang] ? lang : 'en',
    t: (key, ...args) => dict[key].replace(/\{(\d+)\}/g, (_m, i) => String(args[Number(i)] ?? '')),
  };
}
