-- At most one live category per account, key and type. Partial, so Prisma cannot
-- express it in schema.prisma; this migration is its only definition.
CREATE UNIQUE INDEX "categories_account_system_key_type_live_key"
  ON "categories" ("account_id", "system_key", "type")
  WHERE "system_key" IS NOT NULL AND "is_deleted" = false;

